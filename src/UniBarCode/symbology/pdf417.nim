proc codewordWidths(cw: int; ci: int): array[8, int] =
  var v = uint32(pdf417Bits[ci * 929 + cw]) shl 1
  var bitsLeft = 17
  for i in 0 ..< 8:
    let cur = (v shr 16) and 1
    var run = 0
    while bitsLeft > 0 and (((v shr 16) and 1) == cur):
      run += 1
      v = v shl 1
      dec bitsLeft
    result[i] = run

# ── Fixed symbol patterns — ISO/IEC 15438:2015 §5.4 ─────────────────────────
# Start: 17 modules, 4 bars + 4 spaces, bar-first.
# Stop:  18 modules, 5 bars + 4 spaces, bar-first, ends with bar.

const
  StartPat: array[8, int] = [8, 1, 1, 1, 1, 1, 1, 3]
  StopPat: array[9, int] = [7, 1, 1, 3, 1, 1, 1, 2, 1]

# ── Row indicator codewords — ISO/IEC 15438:2015 §5.7 ────────────────────────

proc leftRowIndicator(row, numRows, numCols, ecLevel: int): int =
  let g = row div 3
  case row mod 3
  of 0: 30 * g + (numRows - 1) div 3
  of 1: 30 * g + ecLevel * 3 + (numRows - 1) mod 3
  else: 30 * g + (numCols - 1)

proc rightRowIndicator(row, numRows, numCols, ecLevel: int): int =
  let g = row div 3
  case row mod 3
  of 0: 30 * g + (numCols - 1)
  of 1: 30 * g + (numRows - 1) div 3
  else: 30 * g + ecLevel * 3 + (numRows - 1) mod 3

# ── GF(929) Reed-Solomon — ISO/IEC 15438:2015 §5.9 ───────────────────────────

const EcLevelK: array[9, int] = [2, 4, 8, 16, 32, 64, 128, 256, 512]

proc gfMul929(a, b: int): int {.inline.} = (a * b) mod 929
proc gfPow929(base, exp: int): int =
  result = 1; var b = base; var e = exp
  while e > 0:
    if (e and 1) == 1: result = gfMul929(result, b)
    b = gfMul929(b, b); e = e shr 1

proc pdf417RS(data: seq[int]; ecLevel: int): seq[int] =
  let k = EcLevelK[ecLevel]
  var gen = @[1]
  for i in 0 ..< k:
    let fac = (929 - gfPow929(3, i + 1)) mod 929 # root at 3^(i+1)
    var ng = newSeq[int](gen.len + 1)
    for j in 0 ..< gen.len:
      ng[j] = (ng[j] + gfMul929(gen[j], fac)) mod 929
      ng[j+1] = (ng[j+1] + gen[j]) mod 929
    gen = ng
  var e = newSeq[int](k)
  for d in data:
    let t1 = (d + e[k - 1]) mod 929
    for j in countdown(k - 1, 1):
      e[j] = (e[j - 1] + 929 - gfMul929(gen[j], t1)) mod 929
    e[0] = (929 - gfMul929(gen[0], t1)) mod 929
  result = newSeq[int](k)
  for i in 0 ..< k:
    result[i] = (929 - e[k - 1 - i]) mod 929 # negate: LFSR stores -remainder

# ── Byte compaction — ISO/IEC 15438:2015 §5.4.4 ─────────────────────────────

proc byteCompact(payload: string): seq[int] =
  result.add(if payload.len mod 6 == 0: 924 else: 901)
  var i = 0
  while i + 5 < payload.len:
    var v = 0
    for k in 0 ..< 6: v = v * 256 + int(payload[i+k])
    var cws: array[5, int]
    for k in countdown(4, 0): cws[k] = v mod 900; v = v div 900
    for k in 0 ..< 5: result.add(cws[k])
    i += 6
  for j in i ..< payload.len: result.add(int(payload[j]))

# ── Row rendering ─────────────────────────────────────────────────────────────

proc addWidths(bars: var seq[bool]; ws: openArray[int]) =
  var isBar = true
  for w in ws:
    for _ in 0 ..< w: bars.add(isBar)
    isBar = not isBar

proc renderRow(codewords: seq[int]; clusterIdx: int): seq[bool] =
  addWidths(result, StartPat)
  for cw in codewords:
    addWidths(result, codewordWidths(cw, clusterIdx))
  addWidths(result, StopPat)

# ── Public encoder ────────────────────────────────────────────────────────────

proc encode*(payload: string; ecLevel = 2; dataColCount = 3): EncodeResult =
  ## `ecLevel` (0..8) and `dataColCount` (1..30) default to the compact
  ## symbol settings; the dispatcher and C ABI use the defaults.
  if payload.len == 0:
    return encodeError(Symbology, ekValidation, "PDF417 payload must not be empty")
  if ecLevel notin 0..8:
    return encodeError(Symbology, ekValidation, "PDF417 ecLevel must be 0..8")
  if dataColCount notin 1..30:
    return encodeError(Symbology, ekValidation, "PDF417 dataColCount must be 1..30")

  let ecCount = EcLevelK[ecLevel]

  var dataCws = byteCompact(payload)
  dataCws.insert(0, 0)

  if dataCws.len + ecCount > 90 * dataColCount:
    return encodeError(Symbology, ekValidation,
      "PDF417: payload too large for symbol (max ~312 bytes at default settings)")

  var numRows = max(3, (dataCws.len + ecCount + dataColCount -
      1) div dataColCount)
  if numRows > 90: numRows = 90

  let targetLen = numRows * dataColCount - ecCount
  # The first data codeword is the count of data codewords, and a codeword
  # holds 0..928. The capacity check above bounds the payload against the
  # symbol's rows and columns, not against that ceiling: at dataColCount = 30
  # a large payload reaches a targetLen near 1200, which would be written into
  # dataCws[0] as a value no reader can decode.
  if targetLen > 928:
    return encodeError(Symbology, ekValidation,
      "PDF417: " & $targetLen & " data codewords exceeds the 928 a symbol holds")
  while dataCws.len < targetLen: dataCws.add(900)
  # Invariant: targetLen >= dataCws.len (the capacity check above bounds
  # numRows so the pad loop reaches exactly targetLen), so this slice is an
  # identity and the length descriptor below is consistent.
  dataCws = dataCws[0 ..< targetLen]
  dataCws[0] = dataCws.len

  let ec = pdf417RS(dataCws, ecLevel)
  let allCws = dataCws & ec

  var grid: seq[seq[bool]]
  for r in 0 ..< numRows:
    let ci = r mod 3
    var rowCws = @[leftRowIndicator(r, numRows, dataColCount, ecLevel)]
    for c in 0 ..< dataColCount:
      let idx = r * dataColCount + c
      rowCws.add(if idx < allCws.len: allCws[idx] else: 900)
    rowCws.add(rightRowIndicator(r, numRows, dataColCount, ecLevel))
    grid.add(renderRow(rowCws, ci))

  encodeOk(Symbology, payload, BarcodeModules(grid: grid), BarcodeLayout())









